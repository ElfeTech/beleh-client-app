/**
 * Match free-form country values (names, common variants, ISO codes) against
 * the Natural Earth feature names shipped in world-atlas.
 */

export function normalizeCountryKey(raw: string): string {
  return raw
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
}

