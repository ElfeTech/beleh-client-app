/**
 * Resolve a location string against an index of normalized feature names.
 * Exact (after aliasing) wins; otherwise a unique prefix match either way
 * (handles "United States" ⊂ "United States of America" and NE abbreviations).
 */
export function matchCountryKey(index: ReadonlySet<string>, location: string): string | null {
  const raw = normalizeCountryKey(location);
  if (!raw) return null;
  const q = COUNTRY_ALIASES[raw] ?? raw;
  if (index.has(q)) return q;
  let found: string | null = null;
  for (const key of index) {
    if (key.startsWith(q) || q.startsWith(key)) {
      if (found && found !== key) return null; // ambiguous
      found = key;
    }
  }
  return found;
}
